<?php
// results-functions.php

declare(strict_types=1);

function split_signed_int(int $value): array
{
    return [
        "is_negative" => ($value < 0),
        "abs" => abs($value),
        "sign" => ($value < 0) ? "−" : "+",
    ];
}

function format_signed_int_txt(int $value): string
{
    $parts = split_signed_int($value);

    return $parts["sign"] . " " . (string) $parts["abs"];
}

function format_signed_float(float $value, int $decimals): string
{
    $prefix = ($value < 0) ? "−" : "+";

    return $prefix . number_format(abs($value), $decimals);
}

function format_roll_summary(string $label, int $modifier, string $modeLabel): string
{
    $out = $label;

    if ($modifier !== 0) {
        $out .= " " . format_signed_int_txt($modifier);
    }

    if ($modeLabel !== "") {
        $out .= ", " . $modeLabel;
    }

    return $out;
}

/** Render one die from the canonical result structure. */
function render_die_chip_html(array $die, bool $isFudge): string
{
    $classes = ["die-chip"];

    if (empty($die["kept"])) {
        $classes[] = "is-dropped";
    }

    $role = (string) ($die["role"] ?? "normal");

    if ($role !== "normal") {
        $classes[] = "is-special";
    }

    $value = (int) ($die["value"] ?? 0);

    if ($isFudge) {
        $text = $value < 0 ? "−" : ($value > 0 ? "+" : "0");
    } else {
        $text = (string) $value;
    }

    $statusLabels = [];
    $roleLabels = [
        "wild" => "wild die",
        "wild_explosion" => "wild die explosion",
        "stunt" => "stunt die",
    ];

    if (isset($roleLabels[$role])) {
        $statusLabels[] = $roleLabels[$role];
    }

    if (empty($die["kept"])) {
        $statusLabels[] = "dropped";
    }

    $screenReaderStatus = $statusLabels === []
        ? ""
        : '<span class="sr-only"> (' . h(implode(", ", $statusLabels)) . ')</span>';

    return '<span class="' . h(implode(" ", $classes)) . '">'
        . h($text)
        . $screenReaderStatus
        . '</span>';
}

function render_modifier_html(int $modifier): string
{
    if ($modifier === 0) {
        return "";
    }

    $parts = split_signed_int($modifier);
    $class = $parts["is_negative"] ? "mod-penalty" : "mod-bonus";

    return '<span class="roll-modifier ' . h($class) . '">'
        . h($parts["sign"] . " " . (string) $parts["abs"])
        . '</span>';
}

/**
 * Render a pool as arithmetic. Totals are deliberately not calculated here;
 * the canonical dice_total and total values generated by roll.php are final.
 */
function render_pool_expression_html(array $result, int $operator): string
{
    $dice = is_array($result["dice"] ?? null) ? $result["dice"] : [];
    $isFudge = ((string) ($result["die_kind"] ?? "normal") === "fudge");
    $operatorText = ($operator < 0) ? "−" : "+";

    $out = '<div class="expression-line">';
    $out .= '<span class="pool-operator" aria-label="'
        . h($operator < 0 ? "minus" : "plus")
        . '">'
        . h($operatorText)
        . '</span>';
    $out .= '<div class="pool-expression">';
    $out .= '<div class="dice-chip-wrap">';

    foreach ($dice as $die) {
        if (is_array($die)) {
            $out .= render_die_chip_html($die, $isFudge);
        }
    }

    $out .= '</div>';
    $out .= render_modifier_html((int) ($result["modifier"] ?? 0));
    $out .= '</div>';
    $out .= '</div>';

    return $out;
}

function render_special_note_html(array $result): string
{
    $special = is_array($result["special"] ?? null)
        ? $result["special"]
        : null;

    if ($special === null) {
        return "";
    }

    $kind = (string) ($special["kind"] ?? "");

    if ($kind === "stunt") {
        return "Stunt die: "
            . '<span class="detail-roll">'
            . h((string) ((int) ($special["value"] ?? 0)))
            . '</span>';
    }

    if ($kind === "wild") {
        if (!empty($special["complication"])) {
            return "Wild complication: the wild 1 and highest other die ("
                . h((string) ((int) ($special["removed_highest"] ?? 0)))
                . ") were removed.";
        }

        $sequence = is_array($special["sequence"] ?? null)
            ? array_values($special["sequence"])
            : [];

        if (count($sequence) > 1) {
            return "Wild die: "
                . h(implode(" + ", array_map("intval", $sequence)))
                . ".";
        }

        return "Wild die: "
            . h((string) ((int) ($sequence[0] ?? 0)))
            . ".";
    }

    return "";
}
